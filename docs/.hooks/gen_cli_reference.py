#!/usr/bin/env python3
"""Make the Markdown command-line reference from the `--help` text of each command, and print it.

Each argument is one command, split as a shell would split it. A command that fails to print its help
gets a warning box on the page instead of stopping the docs build. A command that starts with "python"
runs with the Python of this script, so it also works where only "python3" exists.
docs/.hooks/prebuild.py runs this script on each docs build.

Examples
--------
python gen_cli_reference.py --cwd . "python bin/check_chunk.py" "python bin/merge_features.py"
"""

import argparse
import os
import shlex
import subprocess
import sys


def slug(text):
    """Make an anchor name for a heading.

    Parameters
    ----------
    text : str
        The heading text, for example "check_chunk.py".

    Returns
    -------
    str
        Lower case, with each character that is not a letter or digit replaced by "-".
    """
    return "".join(c if c.isalnum() else "-" for c in text.lower()).strip("-")


def first_line(help_text):
    """Find the description in a help text: its first paragraph that is not a usage or options paragraph.

    Parameters
    ----------
    help_text : str
        The --help output of a command.

    Returns
    -------
    str
        The paragraph on one line, or "" if there is none.
    """
    paras = [p.strip() for p in help_text.split("\n\n") if p.strip()]
    for p in paras:
        if not p.lower().startswith("usage") and not p.lower().startswith(
            ("options", "positional", "optional")
        ):
            return " ".join(p.split())
    return ""


def main():
    """Run each command with --help and print the reference page."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cwd", default=".")
    ap.add_argument("--timeout", type=int, default=60)
    ap.add_argument("commands", nargs="+")
    a = ap.parse_args()

    # A fixed width and no colors make the same help text on each computer.
    env = {**os.environ, "COLUMNS": "100", "NO_COLOR": "1", "TERM": "dumb"}
    sections, summary = [], []
    for cmd in a.commands:
        name = cmd.split()[-1] if cmd.startswith("python ") else cmd
        name = os.path.basename(name) if cmd.startswith("python ") else name
        argv = shlex.split(cmd)
        if argv[0] == "python":
            argv[0] = sys.executable
        try:
            res = subprocess.run(
                [*argv, "--help"], cwd=a.cwd, capture_output=True, text=True, timeout=a.timeout, env=env
            )
            text = (res.stdout or res.stderr).rstrip()
            ok = res.returncode == 0 and text
        except (OSError, subprocess.TimeoutExpired) as e:
            text, ok = f"{type(e).__name__}: {e}", False
        desc = first_line(text) if ok else ""
        summary.append(f"| [`{name}`](#{slug(name)}) | {desc.replace('|', '/')} |")
        body = [f"## {name} {{ #{slug(name)} }}", "", f"```bash\n{cmd} --help\n```", ""]
        if ok:
            body += ["```text", text, "```", ""]
        else:
            body += [
                '!!! warning "Help text unavailable"',
                f"    `{cmd} --help` failed in the docs build. Install the tool's dependencies in the docs "
                "job or fix the command.",
                "",
                "    ```text",
            ]
            body += ["    " + line for line in text.splitlines()[-15:]] + ["    ```", ""]
        sections.append("\n".join(body))

    print(
        "\n".join(
            [
                "# Command-line reference",
                "",
                "<!-- GENERATED by gen_cli_reference.py from each command's --help: edit the help text in "
                "the code, not this page. -->",
                "",
                "| Command | Description |",
                "|---|---|",
                *summary,
                "",
                *sections,
            ]
        )
    )


if __name__ == "__main__":
    main()
